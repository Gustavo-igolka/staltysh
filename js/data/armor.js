const ATLAS_IDS = (() => {
  const stem = ATLAS_STEM.map((_, i) => mkId(i, 'cm'));
  const atlasTop = ATLAS_TOP.map((_, i) => mkId(i + 4, 'cm'));
  const oracleTop = ORACLE_TOP.map((_, i) => mkId(i + 4, 'cm'));
  ATLAS_STEM.forEach((row, i) => ARMOR.push(def(stem[i], row, 'combo', i, {
    cost: stepCost('atlas', i, 1500),
    next: i < 3 ? [stem[i + 1]] : [atlasTop[0], oracleTop[0]],
    price: i === 0 ? 1500 : 0,
  })));
  ATLAS_TOP.forEach((row, i) => ARMOR.push(def(atlasTop[i], row, 'combo', i + 4, {
    cost: stepCost('atlas', i + 4, 0), next: i < 2 ? [atlasTop[i + 1]] : [], lore: 'atlas',
  })));
  ORACLE_TOP.forEach((row, i) => ARMOR.push(def(oracleTop[i], row, 'combo', i + 4, {
    cost: stepCost('oracle', i + 4, 0), next: i < 2 ? [oracleTop[i + 1]] : [], lore: 'oracle',
  })));
  return stem;
})();


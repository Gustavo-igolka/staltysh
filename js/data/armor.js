// ── ID по схеме тип_редкость_подкатегория_NN ────────────────
// Редкость: 1 серая (ступени 1–2), 2 синяя (3–4), 3 фиолетовая (5–6), 4 красная (7). NN двузначный, сбрасывается
// на каждой редкости внутри подкатегории (cb/cm/sc/bp). Номера идут в порядке создания: цепочка за цепочкой.
// Красные: Эшка a_4_cb_00, Эмка 01, Диван 02, Сверхтяж 03…06; Атлас a_4_cm_00, Оракул 01, Стриж 02; Нептун a_4_sc_00; Рывок a_4_bp_00.
const counters = {};
function mkId(tier, sub) {
  const rar = tier === 6 ? 4 : Math.floor(tier / 2) + 1;
  const key = `${rar}_${sub}`;
  const n = counters[key] ?? 0;
  counters[key] = n + 1;
  return `a_${rar}_${sub}_${String(n).padStart(2, '0')}`;
}

// ── Сборка предметов ─────────────────────────────────────────
// Возвращает массив описаний предметов (их регистрирует data/items.js) и описания веток для бартера.
const ARMOR = [];

function def(id, row, armorClass, tier, extra) {
  return {
    id, owner: 'locked', type: 'armor', slot: 'armor', armorClass, fixedTier: true, tier,
    name: row.name, w: 2, h: 3, weight: row.weight, durMax: row.durMax, stats: row.stats,
    desc: (tier === 6 && extra.lore ? DESC[extra.lore] : null) ?? STEP_DESC[tier] ?? '', ...extra,
  };
}

// chainKey — ключ весов ресурсов; cost для получения ступени n (1..7)
function stepCost(chainKey, tier, price) {
  if (tier === 0) return { money: price, resources: {} };
  const step = tier + 1;
  const weights = tier === 6 ? RED_RECIPES[chainKey] : CHAIN_WEIGHTS[chainKey];
  return { money: STEP_MONEY[step], step, weights, total: tier === 6 ? null : STEP_RESOURCES[step] };
}

// Линейная цепочка из 7 ступеней
function chain(sub, armorClass, chainKey, price, rows) {
  const ids = rows.map((_, i) => mkId(i, sub));
  rows.forEach((row, i) => {
    ARMOR.push(def(ids[i], row, armorClass, i, {
      cost: stepCost(chainKey, i, price),
      next: i < 6 ? [ids[i + 1]] : [],
      price: i === 0 ? price : 0,
      lore: chainKey,
    }));
  });
  return ids;
}

